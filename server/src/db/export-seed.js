// `npm run db:export-seed` — writes seed.sql (sample routes, stops, buses, fares, schedules
// and the demo staff accounts, without passwords) so it can be pasted into the Supabase SQL editor.
// Safe to run more than once: every insert is ON CONFLICT DO NOTHING.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { PGlite } from '@electric-sql/pglite';
import { seed } from './seed.js';

const dir = path.dirname(fileURLToPath(import.meta.url));
const db = new PGlite();
await db.exec(await readFile(path.join(dir, 'schema.sql'), 'utf8'));
const query = async (s, p = []) => (await db.query(s, p)).rows;
const tx = (fn) => db.transaction((t) => fn({ query: async (s, p = []) => (await t.query(s, p)).rows }));
await seed({ query, tx, demo: false });

const lit = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
};

const TABLES = [
  ['routes', 'id, code, name, active', 'ORDER BY code', '(id)'],
  ['stops', 'id, route_id, seq, name, lat, lng, distance_km, minutes_from_start', 'ORDER BY route_id, seq', '(id)'],
  ['buses', 'id, reg_no, bus_type, layout, total_seats, depot, active', 'ORDER BY reg_no', '(id)'],
  ['fares', 'route_id, bus_type, amount', 'ORDER BY route_id, bus_type', '(route_id, bus_type)'],
  ['schedules', 'id, service_no, route_id, bus_id, departure_time::text AS departure_time, days, active', 'ORDER BY service_no', '(id)'],
  ['users', 'name, email, phone, role', 'ORDER BY email', ''],
];

let out = '-- GovBus sample data (generated by `npm run db:export-seed`). Run after schema.sql.\n-- Re-running is safe: existing rows are left alone.\nBEGIN;\n';
for (const [table, cols, order, conflict] of TABLES) {
  const rows = await query(`SELECT ${cols} FROM ${table} ${order}`);
  const names = Object.keys(rows[0]);
  out += `\n-- ${table} (${rows.length})\nINSERT INTO ${table} (${names.join(', ')}) VALUES\n`;
  out += rows.map((r) => `  (${names.map((n) => lit(r[n])).join(', ')})`).join(',\n');
  out += `\nON CONFLICT ${conflict} DO NOTHING;\n`;
}
out += '\nCOMMIT;\n';
await writeFile(path.join(dir, 'seed.sql'), out);
console.log(`Wrote ${path.join(dir, 'seed.sql')}`);
process.exit(0);
